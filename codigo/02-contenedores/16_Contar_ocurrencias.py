#Dada una lista que contiene números repetidos, determine cuántas veces aparece un
#número específico utilizando count().

numeros = [1, 2, 3, 2, 4, 2, 5]
numero_a_contar = 2
ocurrencias = numeros.count(numero_a_contar)
print(f"El número {numero_a_contar} aparece {ocurrencias} veces en la lista.")

