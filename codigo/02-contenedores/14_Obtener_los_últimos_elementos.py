#Dada una lista de números, utilice slicing para obtener y mostrar sus tres últimos elementos.
numeros = [10, 20, 30, 40, 50]
# Obtener los tres últimos elementos utilizando slicing 
tres_ultimos = numeros[-3:]
print("Los tres últimos elementos son:", tres_ultimos) 

tres_ultimos = numeros[2:5]
print("Los tres últimos elementos son:", tres_ultimos)

