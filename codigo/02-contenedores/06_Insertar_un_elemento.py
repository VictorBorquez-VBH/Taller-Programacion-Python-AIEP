#Dada una lista de ciudades, inserte una nueva ciudad en una posición específica utilizando el método insert().
ciudades = ["Lima", "Madrid", "París"]
print("Lista original de ciudades:", ciudades)
# Insertar "Tokio" en la posición 1 (segunda posición)
ciudades.insert(1, "Tokio")
print("Lista de ciudades después de insertar Tokio:", ciudades) 


