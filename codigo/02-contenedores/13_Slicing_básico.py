#Dada una lista de números, obtenga mediante slicing los tres primeros elementos y muestre el resultado.
numeros = [10, 20, 30, 40, 50]
# Obtener los tres primeros elementos utilizando slicing
tres_primeros = numeros[:3]
print("Los tres primeros elementos son:", tres_primeros) 

tres_primeros = numeros[0:3]
print("Los tres primeros elementos son:", tres_primeros)
